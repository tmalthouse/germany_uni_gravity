"""
father_profession_canonicalizer.py
===================================

Single-file, drop-in module for canonicalizing noisy, OCR'd, genitive-case
German father-profession strings (e.g. from a 19th-century Hessian
address-book / matriculation register) into clean, Titlecased,
nominative-singular German profession names -- both as a plain Python
function and as a fast, vectorized Polars column transform.

Contents
--------
1. `canonicalize_entry(raw: str) -> str`
   The heuristic parser: cleans OCR artifacts/abbreviations, strips place
   names, deceased-markers and given names, splits "u./und" conjunctions
   into multiple professions (semicolon-joined), and looks up (or
   lemmatizes) the profession noun. Returns "Unknown" when nothing
   profession-like survives.

2. `PROFESSION_CANONICAL_MAP`
   A precomputed dict covering every distinct raw string from the
   original ~2,660-row frequency table this was built against, produced
   by running `canonicalize_entry` once and hand-correcting a few
   ambiguous cases (e.g. "Prof. Dr." -> "Professor", not
   "Professor; Doktor"; "Doktor" reserved for medical contexts like
   "Dr. med."). Using this dict directly is what makes the Polars
   integration below fully vectorized rather than a per-row Python call.

3. Polars integration -- `canonical_expr()` / `canonicalize_column()`
   `canonical_expr()` is a single vectorized `Expr.replace_strict(...)`
   call (no `.map_elements()`/`.apply()` involved). `canonicalize_column()`
   wraps it for the common case, and only falls back to calling
   `canonicalize_entry()` -- and only on the *distinct* values not already
   covered by the dict, not on every row -- when it encounters strings
   that were never seen when the map was built.

Usage
-----
    from father_profession_canonicalizer import canonicalize_entry
    canonicalize_entry("Pfarrers Friedrich")   # -> "Pfarrer"

    import polars as pl
    from father_profession_canonicalizer import canonicalize_column

    df = pl.DataFrame({"father_profession": [...]})
    df = canonicalize_column(df, "father_profession")
    # -> adds a "father_profession_canonical" column

This module has no hard dependency on Polars: the Polars-related imports
only happen inside `canonical_expr`/`canonicalize_column`, so importing
just `canonicalize_entry` / `PROFESSION_CANONICAL_MAP` works fine in a
plain-Python (non-Polars) project too.
"""


def canonical_expr(column: str, mapping: dict | None = None) -> "pl.Expr":
    """
    A single vectorized Polars expression that maps `column` through the
    canonicalization dictionary. Unknown/unmapped values become null (so
    callers can tell "known unknown" (the string "Unknown", i.e. genuinely
    unparseable input) apart from "not in the map at all" (null)).

    This is a plain dict-substitution pushed down into Polars' Rust
    execution engine via `Expr.replace_strict` -- no Python function is
    called per row.
    """
    import polars as pl

    mapping = mapping if mapping is not None else PROFESSION_CANONICAL_MAP
    return pl.col(column).replace_strict(mapping, default=None, return_dtype=pl.Utf8)


def canonicalize_column(
    df,
    column: str,
    out_column: str | None = None,
    *,
    persist_new_mappings: bool = True,
    persist_path: str | None = None,
):
    """
    Add a canonicalized version of `column` to a Polars DataFrame (or
    LazyFrame -- everything used here is lazy-safe).

    Parameters
    ----------
    df : pl.DataFrame | pl.LazyFrame
    column : name of the source string column (raw profession strings).
    out_column : name of the new column (default: f"{column}_canonical").
    persist_new_mappings : if True (default), any previously-unseen values
        encountered are parsed once with the heuristic fallback parser and
        merged into the in-memory PROFESSION_CANONICAL_MAP, so repeated
        calls within the same process hit the fast vectorized path.
    persist_path : optional path to a JSON file. If given, newly-learned
        mappings are also merged into (and written back to) that file, so
        future *processes* skip the fallback parser too. Off by default
        since a single-file drop-in has no companion file to write to.

    Returns
    -------
    Same type as `df`, with the extra canonical column added.
    """
    import polars as pl

    is_lazy = isinstance(df, pl.LazyFrame)
    lf = df.lazy() if is_lazy else df.lazy()  # work lazily either way

    out_column = out_column or f"{column}_canonical"

    # --- Pass 1: fully vectorized dictionary lookup (fast path) ---------
    lf = lf.with_columns(canonical_expr(column).alias(out_column))

    # Collecting only the distinct unmatched values is cheap even on huge
    # tables (it's a `unique()` over what should be a tiny residual slice),
    # and it's the only place we need to leave the lazy/vectorized world.
    unmatched = (
        lf.filter(pl.col(out_column).is_null() & pl.col(column).is_not_null())
        .select(column)
        .unique()
        .collect()
        .get_column(column)
        .to_list()
    )

    if unmatched:
        # Run the (comparatively slow) heuristic parser only on the
        # handful of distinct novel strings -- never on every row.
        fallback_map = {v: canonicalize_entry(v) for v in unmatched}

        lf = lf.with_columns(
            pl.when(pl.col(out_column).is_null())
            .then(canonical_expr(column, fallback_map))
            .otherwise(pl.col(out_column))
            .alias(out_column)
        )

        if persist_new_mappings:
            PROFESSION_CANONICAL_MAP.update(fallback_map)

        if persist_path:
            path = Path(persist_path)
            on_disk = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
            on_disk.update(fallback_map)
            path.write_text(json.dumps(on_disk, ensure_ascii=False, indent=1), encoding="utf-8")

    return lf if is_lazy else lf.collect()

def clean_raw(s: str) -> str:
    s = s.strip().strip('"')
    for pat, rep in OCR_FIXES:
        s = re.sub(pat, rep, s)
    s = s.strip(" ,:;'\"")  # NOTE: trailing '.' is kept - it's meaningful
    return s                # for abbreviations like "Dr.", "Dr.jur.", "Prof."


def strip_deceased(s: str) -> str:
    low = s
    for m in DECEASED_MARKERS:
        low = re.sub(re.escape(m), "", low, flags=re.IGNORECASE)
    return low


def strip_place_phrases(s: str) -> str:
    # remove "zu/in/von/aus/bei/im/am <Capitalized word(s)>" style tails
    s = re.sub(
        r"\b(zu|in|von|aus|bei|im|am|zn)\s+[A-ZÄÖÜ][\wÄÖÜäöüß\-\.]*"
        r"(\s+[A-ZÄÖÜ][\wÄÖÜäöüß\-\.]*)*",
        "",
        s,
    )
    return s


def strip_ordinals(s: str) -> str:
    return re.sub(r"^\s*\d+\.\s*", "", s)


def expand_abbrevs(s_lower: str) -> str:
    for pat, rep in ABBR_EXPANSIONS:
        s_lower = re.sub(pat, rep, s_lower)
    return s_lower


def strip_names_and_initials(tokens):
    out = []
    for t in tokens:
        bare = t.strip(".,:;")
        low = bare.lower()
        if low in FIRST_NAMES:
            continue
        if re.fullmatch(r"[A-Za-zÄÖÜäöüß]\.?", t):  # single-letter initial
            continue
        if re.fullmatch(r"\d+\.?", t):
            continue
        # keep the original token (with trailing period) so abbreviations
        # like "Dr.jur." still match STEM_MAP; only strip stray commas
        out.append(t.strip(",;"))
    return out


def _titlecase_preserve(w: str) -> str:
    """Uppercase the first letter of w (and of each part after a hyphen),
    without lowercasing the rest of the string (so internal caps in
    compounds like 'GutsBesitzer'-style OCR artifacts, or hyphenated
    words, survive)."""
    parts = w.split("-")
    fixed = []
    for p in parts:
        if p:
            fixed.append(p[0].upper() + p[1:])
        else:
            fixed.append(p)
    return "-".join(fixed)


def fallback_lemmatize(word: str) -> str:
    """Generic genitive -> nominative un-inflection for German agent nouns."""
    w = word
    low = w.lower()
    if low.endswith("raths") or low.endswith("rathe") or low.endswith("ratha"):
        base = w[:-1]
        base = re.sub(r"rath[ea]?$", "rat", base, flags=re.IGNORECASE)
        return _titlecase_preserve(base)
    if low.endswith("es") and len(w) > 4:
        return _titlecase_preserve(w[:-2])
    if low.endswith("ers"):
        return _titlecase_preserve(w[:-1])
    if low.endswith("en") and len(w) > 4:
        return _titlecase_preserve(w[:-2])
    if low.endswith("s") and not low.endswith("us") and len(w) > 3:
        return _titlecase_preserve(w[:-1])
    return _titlecase_preserve(w)


def canonical_word(word: str) -> str:
    key = word.lower().strip(",;:")
    if key in STEM_MAP:
        return STEM_MAP[key]
    if key.rstrip(".") in STEM_MAP:
        return STEM_MAP[key.rstrip(".")]
    return fallback_lemmatize(word)


def canonicalize_entry(raw: str) -> str:
    s = clean_raw(raw)
    if s == "":
        return "Unknown"
    s = strip_ordinals(s)
    s = strip_deceased(s)
    s = strip_place_phrases(s)
    s = s.strip(" ,;:-")
    if s == "":
        return "Unknown"

    # try whole-string lookup first (handles multi-word canonical phrases,
    # abbreviation combos like "Prof. Dr.", "Dr. med.")
    whole_key = re.sub(r"\s+", " ", s.lower()).strip(" ,;:-")
    if whole_key in STEM_MAP:
        return STEM_MAP[whole_key]
    if whole_key.rstrip(".") in STEM_MAP:
        return STEM_MAP[whole_key.rstrip(".")]

    # split on conjunctions -> multiple professions
    parts = re.split(r"\s+u\.\s+|\s+und\s+", s)
    results = []
    for part in parts:
        part = part.strip(" ,;:-")
        if part == "":
            continue
        low_part = expand_abbrevs(part.lower())
        low_part = re.sub(r"\s+", " ", low_part).strip()
        if low_part in STEM_MAP or low_part.rstrip(".") in STEM_MAP:
            results.append(STEM_MAP.get(low_part, STEM_MAP.get(low_part.rstrip("."))))
            continue
        tokens = part.split()
        tokens = strip_names_and_initials(tokens)
        if not tokens:
            continue
        # try full remaining phrase (helps "Prof. Dr." etc.)
        joined = " ".join(tokens).lower().strip(",;:")
        if joined in STEM_MAP or joined.rstrip(".") in STEM_MAP:
            results.append(STEM_MAP.get(joined, STEM_MAP.get(joined.rstrip("."))))
            continue
        # head noun heuristic: the LAST token is usually the profession noun
        # (given names/initials that survived filtering tend to precede it,
        # OCR noise aside); but many entries are "Profession FirstName" so
        # try first token if it looks like a profession-ish (longer) word
        cand = None
        for t in tokens:
            tl = t.lower()
            if tl in STEM_MAP:
                cand = STEM_MAP[tl]
                break
        if cand is None:
            # take first token as the head profession word (most common
            # pattern in this data: "Beruf Vorname(n)")
            head = tokens[0]
            if len(head) < 3 or not re.search(r"[A-Za-zÄÖÜäöüß]", head):
                cand = None
            else:
                cand = canonical_word(head)
        if cand:
            results.append(cand)

    if not results:
        return "Unknown"
    # de-duplicate while preserving order
    seen = set()
    ordered = []
    for r in results:
        if r not in seen:
            seen.add(r)
            ordered.append(r)
    return "; ".join(ordered)


